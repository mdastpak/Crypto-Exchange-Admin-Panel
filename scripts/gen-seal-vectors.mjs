// Generates src/crypto/vectors.json with Node's OpenSSL, independent of the WebCrypto code under test.
// Run: node scripts/gen-seal-vectors.mjs
import { createCipheriv, createECDH, createPrivateKey, createPublicKey, diffieHellman, hkdfSync } from 'node:crypto'
import { writeFileSync } from 'node:fs'

const b64u = (b) => Buffer.from(b).toString('base64url')
// Fixed private scalars: test data only, never used outside the tests.
const clientPriv = Buffer.alloc(32, 0x11)
const serverPriv = Buffer.alloc(32, 0x22)
const jwk = (priv) => {
  const e = createECDH('prime256v1'); e.setPrivateKey(priv)
  const pub = e.getPublicKey()
  return { kty: 'EC', crv: 'P-256', x: b64u(pub.subarray(1, 33)), y: b64u(pub.subarray(33, 65)), d: b64u(priv) }
}
const c = jwk(clientPriv), s = jwk(serverPriv)
const priv = (j) => createPrivateKey({ key: j, format: 'jwk' })
const pubOf = (j) => createPublicKey({ key: { kty: j.kty, crv: j.crv, x: j.x, y: j.y }, format: 'jwk' })
const shared = diffieHellman({ privateKey: priv(c), publicKey: pubOf(s) })
const sharedBack = diffieHellman({ privateKey: priv(s), publicKey: pubOf(c) })
if (!shared.equals(sharedBack)) throw new Error('ECDH mismatch')
const sid = 'sess-0001'
const key = Buffer.from(hkdfSync('sha256', shared, Buffer.from(sid), Buffer.from('cex-admin-seal-v1'), 32))

const ctx = { kid: 'k_test_1', sid, direction: 'req', seq: 7, method: 'POST', path: '/admin/users/query', requestId: 'req-0001' }
const aad = Buffer.from([1, ctx.kid, ctx.sid, ctx.direction, ctx.seq, ctx.method, ctx.path, ctx.requestId].join('|'))
const iv = Buffer.from('000102030405060708090a0b', 'hex')
const plaintext = JSON.stringify({ ts: 1_760_000_000_000, data: { email: 'user1@mail.example' } })
const cipher = createCipheriv('aes-256-gcm', key, iv)
cipher.setAAD(aad)
const ct = Buffer.concat([cipher.update(plaintext, 'utf8'), cipher.final(), cipher.getAuthTag()])

writeFileSync(new URL('../src/crypto/vectors.json', import.meta.url), JSON.stringify({
  note: 'Generated by scripts/gen-seal-vectors.mjs with Node crypto (OpenSSL). Test data only.',
  clientJwk: c, serverJwk: s, sid, sharedSecretHex: shared.toString('hex'), keyHex: key.toString('hex'),
  context: ctx, aad: aad.toString(), ivHex: iv.toString('hex'), plaintext, ts: 1_760_000_000_000, ct: b64u(ct),
}, null, 2) + '\n')
console.log('wrote src/crypto/vectors.json')
